func TestParseAndString(t *testing.T) {
	// Expected values were produced by Decimal(string:locale:).description.
	cases := map[string]string{
		"12abc": "12", "1,5": "1", " 5": "5", "5 ": "5", "-": "0", "1.2.3": "1.2", ".5": "0.5", "5.": "5",
		"1e2": "100", "+5": "5", "0x10": "0", "-0": "0", "0.000": "0", "00012": "12", "5e": "5", "5e+": "5",
		"1 2": "1", "1.5e1": "15", "-.5": "-0.5", "--5": "0", "100.00": "100", "1E+3": "1000", "123.456000": "123.456",
		"12345678901234567890123456789012345678901234567890":   "12345678901234567890123456789012345678900000000000",
		"0.12345678901234567890123456789012345678901234567890": "0.123456789012345678901234567890123456789",
		"9999999999999999999999999999999999999999":             "9999999999999999999999999999999999999900",
	}
	for in, want := range cases {
		got, err := Parse(in)
		if err != nil || got.String() != want {
			t.Errorf("Parse(%q) = %q, %v; want %q", in, got, err, want)
		}
	}
	for _, in := range []string{"", "abc", "NaN", "inf", "1e400", "1E-400"} {
		if _, err := Parse(in); err == nil {
			t.Errorf("Parse(%q) succeeded", in)
		}
	}
}

func TestLimits(t *testing.T) {
	a := MustParse("340282366920938463463374607431768211455")
	if got := a.Add(FromInt(1)).String(); got != "340282366920938463463374607431768211450" {
		t.Errorf("a+1 = %s", got)
	}
	if got := a.Mul(FromInt(2)).String(); got != "680564733841876926926749214863536422910" {
		t.Errorf("a*2 = %s", got)
	}
	if got := FromInt64(9223372036854775807).Mul(FromInt64(9223372036854775807)).String(); got != "85070591730234615847396907784232501249" {
		t.Errorf("max*max = %s", got)
	}
	if got := FromInt(7).Div(FromInt(3)).String(); got != "2.33333333333333333333333333333333333333" {
		t.Errorf("7/3 = %s", got)
	}
	if got := FromInt(1).Div(FromInt(1_000_000)).String(); got != "0.000001" {
		t.Errorf("1/1e6 = %s", got)
	}
}

func TestJSON(t *testing.T) {
	var d Decimal
	for in, want := range map[string]string{
		"0.1": "0.1", "0.123456789012345678901234567890": "0.12345678901234567890123456789", "1e3": "1000", "-0.5": "-0.5",
		"123456789012345678901234567890123456789": "123456789012345678901234567890123456789", "1E-7": "0.0000001",
	} {
		if err := json.Unmarshal([]byte(in), &d); err != nil || d.String() != want {
			t.Errorf("unmarshal %s = %s, %v; want %s", in, d, err, want)
		}
	}
	for _, in := range []string{`"1.5"`, `null`, `true`} {
		if err := json.Unmarshal([]byte(in), &d); err == nil {
			t.Errorf("unmarshal %s succeeded", in)
		}
	}
	b, _ := json.Marshal(struct {
		V Decimal `json:"v"`
	}{MustParse("4.00004")})
	if string(b) != `{"v":4.00004}` {
		t.Errorf("marshal = %s", b)
	}
}

// TestSwiftGolden replays testdata/decimal_golden.txt, generated by the Swift
// implementation: "<price in> <cached> <out> <uncached> <cachedTok> <outTok>
// <cost description> <cost json> <3x sum description>". Costs follow
// Decimal(n)/1_000_000*price summed in the same order as Swift.
func TestSwiftGolden(t *testing.T) {
	f, err := os.Open("testdata/decimal_golden.txt")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	million := FromInt(1_000_000)
	n := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fs := strings.Fields(sc.Text())
		if len(fs) != 9 {
			t.Fatalf("bad golden line %q", sc.Text())
		}
		price := func(s string) Decimal { return MustParse(s) }
		tok := func(s string) Decimal {
			v, err := strconv.ParseInt(s, 10, 64)
			if err != nil {
				t.Fatal(err)
			}
			return FromInt64(v)
		}
		cost := tok(fs[3]).Div(million).Mul(price(fs[0])).
			Add(tok(fs[4]).Div(million).Mul(price(fs[1]))).
			Add(tok(fs[5]).Div(million).Mul(price(fs[2])))
		sum := Zero.Add(cost).Add(cost).Add(cost)
		js, _ := json.Marshal(struct {
			V Decimal `json:"v"`
		}{cost})
		if cost.String() != fs[6] || string(js) != fs[7] || sum.String() != fs[8] {
			t.Fatalf("line %q: got cost=%s json=%s sum=%s", sc.Text(), cost, js, sum)
		}
		n++
	}
	if n < 2000 {
		t.Fatalf("only %d golden lines", n)
	}
}
